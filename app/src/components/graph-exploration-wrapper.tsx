interface GraphExplorationWrapperProps {
  widgetId: string;
  nodes: GraphNode[];
  edges: GraphEdge[];
  connectionId: string;
  /** The widget's saved per-card database: neighbours are looked up where the
   *  graph was queried (#1824). */
  database?: string;
  settings: Record<string, unknown>;
  onChartClick?: (point: Record<string, unknown>) => void;
  /** Server-generated hash of the query that produced this data.
   *  Used to detect when the query changed so stale exploration state
   *  can be discarded. */
  resultId?: string;
  /** The connector that ran that query, as its result names it (#2061). */
  connectorType?: string;
  /** When true, triggers a fit-to-viewport after mount with a short delay. */
  autoFit?: boolean;
}

interface NodeMenu {
  node: GraphNode;
  x: number;
  y: number;
}

function NodeContextMenu({
  menu,
  onClose,
  onExpand,
  onCollapse,
  onProperties,
}: Readonly<{
  menu: NodeMenu;
  onClose: () => void;
  onExpand?: () => void;
  onCollapse?: () => void;
  onProperties?: () => void;
}>) {
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const handleOutside = (e: MouseEvent) => {
      if (ref.current && !ref.current.contains(e.target as Node)) onClose();
    };
    const handleKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
    };
    document.addEventListener("mousedown", handleOutside);
    document.addEventListener("keydown", handleKey);
    return () => {
      document.removeEventListener("mousedown", handleOutside);
      document.removeEventListener("keydown", handleKey);
    };
  }, [onClose]);

  // A synthetic node was computed by the query, not read from the database, so
  // there is nothing to fetch neighbours from. Drop the affordance here rather
  // than relying on canExpand alone: only the menu can give the reason, and a
  // boolean cannot (#1361).
  const synthetic = menu.node.synthetic === true;

  const items = [
    onProperties && { label: "Properties", action: onProperties },
    onExpand && !synthetic && { label: "Expand", action: onExpand },
    onCollapse && { label: "Collapse", action: onCollapse },
  ].filter(Boolean) as { label: string; action: () => void }[];

  return (
    <div
      ref={ref}
      data-testid="graph-context-menu"
      className="absolute z-[500] min-w-[160px] rounded-md border bg-popover p-1 text-popover-foreground shadow-md text-sm"
      style={{ left: menu.x, top: menu.y }}
    >
      <div className="px-3 py-1.5 text-xs text-muted-foreground font-medium border-b mb-1">
        {menu.node.label ?? menu.node.id}
      </div>
      {items.length === 0 && (
        <div className="px-3 py-1.5 text-xs text-muted-foreground">
          No actions
        </div>
      )}
      {items.map((item) => (
        <button
          key={item.label}
          onClick={() => {
            item.action();
            onClose();
          }}
          className="flex w-full items-center rounded-sm px-3 py-1.5 text-sm hover:bg-accent hover:text-accent-foreground cursor-pointer"
        >
          {item.label}
        </button>
      ))}
      {synthetic && (
        <div
          data-testid="graph-synthetic-note"
          className="mt-1 border-t px-3 py-1.5 text-xs text-muted-foreground"
        >
          Generated by the query — it is not stored, so it has no neighbours in
          the database to expand.
        </div>
      )}
    </div>
  );
}

/**
 * A property as the panel renders it: by JS shape, structure kept. Rows cross
 * JSON (#1904), so a value is a primitive, a list or a map; nothing else
 * (bigint, symbol, function) survives JSON, so it reads as empty.
 */
function toPropertyValue(v: unknown): PropertyValue {
  if (v === null || v === undefined) return null;
  if (typeof v === "string" || typeof v === "number" || typeof v === "boolean")
    return v;
  if (Array.isArray(v)) return v.map(toPropertyValue);
  if (typeof v === "object")
    return Object.fromEntries(
      Object.entries(v).map(([k, x]) => [k, toPropertyValue(x)]),
    );
  return null;
}

/** A graph element's properties as the inspector lists them (it sorts them). */
function toItems(props: Record<string, unknown> | undefined): PropertyItem[] {
  return Object.entries(props ?? {}).map(([key, value]) => ({
    key,
    value: toPropertyValue(value),
  }));
}

/** An edge's id: its own, else the id the chart gives it by position. */
function edgeKey(edge: GraphEdge, index: number): string {
  return edge.id ?? relationshipId(edge, index);
}

/** What is open in the inspector, by identity: the element is read live from the graph. */
type Inspected = { type: "node"; id: string } | { type: "edge"; key: string };

interface InspectorModel {
  element: InspectorElement;
  elementJson: string;
  connections?: InspectorConnection[];
  /** The relationship to highlight on the canvas. */
  relationshipKey?: string;
}

type NameOf = (id: string) => string;

function buildNodeInspector(
  node: GraphNode,
  nodes: GraphNode[],
  edges: GraphEdge[],
  captionMap: Record<string, string>,
  dark: boolean,
  nameOf: NameOf,
): InspectorModel {
  const { caption, color } = describeGraphNode(node, nodes, captionMap, dark);
  const connections = edges.flatMap((e, i): InspectorConnection[] => {
    const outgoing = e.source === node.id;
    if (!outgoing && e.target !== node.id) return [];
    const otherId = outgoing ? e.target : e.source;
    return [
      {
        id: edgeKey(e, i),
        type: e.label ?? "UNKNOWN",
        direction: outgoing ? "to" : "from",
        otherId,
        otherName: nameOf(otherId),
      },
    ];
  });
  return {
    element: {
      kind: "node",
      id: node.id,
      databaseId: node.id,
      title: caption,
      color,
      labels: node.labels ?? [],
      properties: toItems(node.properties),
    },
    elementJson: JSON.stringify(
      {
        kind: "node",
        id: node.id,
        labels: node.labels ?? [],
        properties: node.properties ?? {},
      },
      null,
      2,
    ),
    connections,
  };
}

function buildRelationshipInspector(
  key: string,
  edges: GraphEdge[],
  nameOf: NameOf,
): InspectorModel | null {
  const index = edges.findIndex((e, i) => edgeKey(e, i) === key);
  if (index < 0) return null;
  const edge = edges[index];
  // Both directions between the same two nodes.
  // In id order, not the order a query happened to return them, so "1 of 2"
  // names the same relationship every time.
  const siblings = edges
    .flatMap((e, i) =>
      (e.source === edge.source && e.target === edge.target) ||
      (e.source === edge.target && e.target === edge.source)
        ? [edgeKey(e, i)]
        : [],
    )
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  const type = edge.label ?? "UNKNOWN";
  return {
    element: {
      kind: "relationship",
      id: key,
      // Only a database id is shown and copied; the key is the graph's own.
      databaseId: edge.id,
      title: type,
      source: { id: edge.source, name: nameOf(edge.source) },
      target: { id: edge.target, name: nameOf(edge.target) },
      siblings,
      properties: toItems(edge.properties),
    },
    elementJson: JSON.stringify(
      {
        kind: "relationship",
        id: edge.id,
        type,
        source: edge.source,
        target: edge.target,
        properties: edge.properties ?? {},
      },
      null,
      2,
    ),
    relationshipKey: key,
  };
}

/**
 * What the inspector shows for the open element, read from the graph as it is
 * now: the title and colour the canvas uses, a node's connections and a
 * relationship's parallel siblings from the edges already loaded (no query).
 */
function buildInspector(
  inspected: Inspected,
  nodes: GraphNode[],
  edges: GraphEdge[],
  captionMap: Record<string, string>,
  dark: boolean,
): InspectorModel | null {
  const nameOf: NameOf = (id) => {
    const n = nodes.find((x) => x.id === id);
    return n ? graphNodeCaption(n, captionMap) : id;
  };
  if (inspected.type === "edge")
    return buildRelationshipInspector(inspected.key, edges, nameOf);
  const node = nodes.find((n) => n.id === inspected.id);
  return node
    ? buildNodeInspector(node, nodes, edges, captionMap, dark, nameOf)
    : null;
}

export function GraphExplorationWrapper({
  widgetId,
  nodes: initialNodes,
  edges: initialEdges,
  connectionId,
  database,
  settings,
  onChartClick,
  resultId,
  connectorType,
  autoFit,
}: Readonly<GraphExplorationWrapperProps>) {
  const containerRef = useRef<HTMLDivElement>(null);
  const [menu, setMenu] = useState<NodeMenu | null>(null);
  const [inspectedElement, setInspectedElement] = useState<Inspected | null>(
    null,
  );
  const inspectedRef = useRef(inspectedElement);
  // Where the last pointer went down, in the graph's own pixels: it decides
  // which side the inspector docks to, so it never opens over the click.
  const pointerXRef = useRef(0);
  const [side, setSide] = useState<"left" | "right">("right");
  const [graphWidth, setGraphWidth] = useState(0);
  const dark = useDarkMode();
  const storeSetState = useGraphWidgetStore((s) => s.setState);
  const stored = useGraphWidgetStore((s) => s.states[widgetId]);
  // The expanded copy is `<id>--fullscreen`; its tile is `<id>` (#1509).
  const tileId = widgetId.split("--")[0];
  const tile = useGraphWidgetStore((s) => s.states[tileId]);

  // If the stored state was built from a different query (different resultId),
  // discard it so the graph resets to the new data instead of showing stale
  // exploration state. When resultId is undefined (e.g. preview mode without
  // a full query run), always use the incoming data.
  const storedIsValid =
    stored != null && resultId != null && stored.resultId === resultId;

  // Where the same query's graph already settled: the copy's own, else the tile's.
  const seedPositions = [stored, tile].find(
    (st) => st?.resultId === resultId && resultId != null && st.positions,
  )?.positions;

  // How to expand a node is the connector's to say, in its own query language
  // (#2061). The connector is the one the query result names, so whoever could
  // run the query can expand it, listed connection or not. Undefined while the
  // connectors load and for a connector that declares none: then no Expand.
  const declared = useConnector(connectorType)?.graphExpansion;
  // Offered only where the server would accept it (#1828).
  const expansion = useCanExpandGraph(connectionId) ? declared : undefined;

  const fetchNeighbors = useCallback(
    async (node: GraphNode): Promise<FetchNeighborsResult> => {
      if (!expansion) return { nodes: [], edges: [] };
      const res = await limitedFetch("/api/query", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          connectionId,
          query: expansion.query,
          params: { [expansion.nodeIdParam]: node.id },
          ...(database ? { database } : {}),
        }),
      });
      // A viewer bound to the dashboard's own queries (#972) is refused this
      // one, and the server's words assume they wrote it.
      if (res.status === 403) {
        throw new Error(
          "Your access to this dashboard covers its own queries, and expanding a node runs another.",
        );
      }

      const { data: result } = await unwrapFullResponse<{
        data: unknown;
        fields?: unknown;
      }>(res);
      const graphConfig = getChartConfig("graph");
      if (!graphConfig) return { nodes: [], edges: [] };

      const transformed = graphConfig.transform(result.data) as {
        nodes: GraphNode[];
        edges: GraphEdge[];
      };
      return {
        nodes: transformed.nodes ?? [],
        edges: transformed.edges ?? [],
      };
    },
    [connectionId, database, expansion],
  );

  const exploration = useGraphExploration({
    initialNodes: storedIsValid ? stored.nodes : initialNodes,
    initialEdges: storedIsValid ? stored.edges : initialEdges,
    fetchNeighbors,
    maxDepth: 3,
    resultId,
  });

  // Persist exploration state to the store whenever it changes, always
  // recording the current resultId so we can detect stale state next render.
  useEffect(() => {
    storeSetState(widgetId, {
      nodes: exploration.nodes,
      edges: exploration.edges,
      resultId,
    });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [exploration.nodes, exploration.edges]);

  const handleNodeRightClick = useCallback((e: GraphNodeEvent) => {
    const rect = containerRef.current?.getBoundingClientRect();
    const x = e.position.x - (rect?.left ?? 0);
    const y = e.position.y - (rect?.top ?? 0);
    setMenu({ node: e.node, x, y });
  }, []);

  // Keep a ref to the current exploration value so handleNodeSelect stays
  // stable across renders even as exploration.nodes / selection change.
  // Without this, the inline callback would be rebuilt every render,
  // causing GraphChart to see a new prop identity each time.
  const explorationRef = useRef(exploration);
  useEffect(() => {
    // Latest-ref pattern: assigned in an effect because writing refs
    // during render is forbidden by the React compiler (#975). Event
    // handlers only read it after effects have run.
    explorationRef.current = exploration;
  }, [exploration]);

  // Opening picks the side from the last pointer-down; a panel already open
  // keeps its side, so stepping through elements never makes it jump.
  const inspect = useCallback((next: Inspected | null) => {
    if (next && !inspectedRef.current) {
      const w = containerRef.current?.clientWidth ?? 0;
      setSide(
        w > 0 && pointerXRef.current > w - graphInspectorWidth(w)
          ? "left"
          : "right",
      );
    }
    inspectedRef.current = next;
    setInspectedElement(next);
  }, []);

  const closeInspector = useCallback(() => {
    inspect(null);
    explorationRef.current.onNodeSelect([]);
    containerRef.current?.focus({ preventScroll: true });
  }, [inspect]);

  const handleNodeSelect = useCallback(
    (ids: string[]) => {
      explorationRef.current.onNodeSelect(ids);
      const node = explorationRef.current.nodes.find((n) => n.id === ids[0]);
      if (onChartClick && ids.length) {
        onChartClick(node ? graphNodeClickPayload(node) : { nodeId: ids[0] });
      }
      // Open property panel on single-click
      if (ids.length === 1) {
        if (node) inspect({ type: "node", id: node.id });
      } else {
        inspect(null);
      }
    },
    [onChartClick, inspect],
  );

  const handleRelationshipClick = useCallback(
    (event: { edge: GraphEdge }) => {
      const edges = explorationRef.current.edges;
      // The chart hands back the edge it holds; fall back to its id, then its
      // ends and type.
      let index = edges.indexOf(event.edge);
      if (index < 0 && event.edge.id !== undefined)
        index = edges.findIndex((e) => e.id === event.edge.id);
      if (index < 0) {
        index = edges.findIndex(
          (e) =>
            e.source === event.edge.source &&
            e.target === event.edge.target &&
            e.label === event.edge.label,
        );
      }
      if (index >= 0)
        inspect({ type: "edge", key: edgeKey(edges[index], index) });
    },
    [inspect],
  );

  // An end link or a connection row: look at that node or relationship, and
  // mark the node on the canvas. Not a click on the chart, so no click action.
  const inspectNode = useCallback(
    (id: string) => {
      explorationRef.current.onNodeSelect([id]);
      inspect({ type: "node", id });
    },
    [inspect],
  );
  const inspectRelationship = useCallback(
    (key: string) => inspect({ type: "edge", key }),
    [inspect],
  );

  const handleLayoutChange = useCallback(
    (layout: "force" | "circular" | "hierarchical") => {
      storeSetState(widgetId, { layout });
    },
    [storeSetState, widgetId],
  );

  const handlePositionsChange = useCallback(
    (positions: Record<string, { x: number; y: number }>) => {
      storeSetState(widgetId, { positions });
    },
    [storeSetState, widgetId],
  );

  const handleCaptionMapChange = useCallback(
    (captionMap: Record<string, string>) => {
      storeSetState(widgetId, { captionMap });
    },
    [storeSetState, widgetId],
  );

  // The graph's width sets the panel's: a third of it, clamped.
  useEffect(() => {
    const el = containerRef.current;
    if (!el || typeof ResizeObserver === "undefined") return;
    const observer = new ResizeObserver(() => setGraphWidth(el.clientWidth));
    observer.observe(el);
    return () => observer.disconnect();
  }, []);

  // Native listeners: the container is a focus target, not a control.
  useEffect(() => {
    const el = containerRef.current;
    if (!el) return;
    const onPointerDown = (e: PointerEvent) => {
      pointerXRef.current = e.clientX - el.getBoundingClientRect().left;
    };
    const onKeyDown = (e: KeyboardEvent) => {
      if (e.key === "Escape" && inspectedRef.current) closeInspector();
    };
    el.addEventListener("pointerdown", onPointerDown, true);
    el.addEventListener("keydown", onKeyDown);
    return () => {
      el.removeEventListener("pointerdown", onPointerDown, true);
      el.removeEventListener("keydown", onKeyDown);
    };
  }, [closeInspector]);

  const captionMap = stored?.captionMap;
  const inspector = useMemo(
    () =>
      inspectedElement
        ? buildInspector(
            inspectedElement,
            exploration.nodes,
            exploration.edges,
            captionMap ?? {},
            dark,
          )
        : null,
    [inspectedElement, exploration.nodes, exploration.edges, captionMap, dark],
  );
  const inspectorWidth = graphInspectorWidth(graphWidth);

  // The inspected element left the graph (a Collapse): nothing is left to show.
  useEffect(() => {
    if (inspectedElement && !inspector) closeInspector();
  }, [inspectedElement, inspector, closeInspector]);

  return (
    <div
      ref={containerRef}
      tabIndex={-1}
      className="relative h-full w-full rounded focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-inset focus-visible:ring-ring"
      data-testid="graph-exploration"
      // An Esc here closes the inspector only, even inside a dialog.
      data-keeps-escape={inspector ? "" : undefined}
    >
      <GraphChart
        nodes={exploration.nodes}
        edges={exploration.edges}
        selectedNodeIds={exploration.selectedNodeIds}
        onNodeSelect={handleNodeSelect}
        onNodeRightClick={handleNodeRightClick}
        onRelationshipClick={handleRelationshipClick}
        layout={settings.layout as "force" | "circular" | undefined}
        initialLayout={storedIsValid ? stored.layout : undefined}
        initialPositions={seedPositions}
        onPositionsChange={handlePositionsChange}
        initialCaptionMap={storedIsValid ? stored.captionMap : undefined}
        showLabels={settings.showLabels as boolean | undefined}
        showRelationshipLabels={
          settings.showRelationshipLabels as boolean | undefined
        }
        onLayoutChange={handleLayoutChange}
        onCaptionMapChange={handleCaptionMapChange}
        autoFit={autoFit}
        overlayInset={inspector ? { side, width: inspectorWidth } : undefined}
        selectedRelationshipId={inspector?.relationshipKey}
        // This wrapper renders its own status bar below; without this the same
        // counts appeared twice in one widget (#1521).
        showNodeCount={false}
        // Shares the chart's bottom row with its legend, so neither covers the
        // other and Reset stays clickable.
        footer={
          <div
            className="flex items-center gap-3 rounded-md bg-background/80 px-3 py-1.5 text-xs text-muted-foreground backdrop-blur-sm border"
            data-testid="graph-status-bar"
          >
            <span data-testid="graph-node-count">
              {exploration.nodes.length} nodes
            </span>
            <span data-testid="graph-edge-count">
              {exploration.edges.length} edges
            </span>
            {exploration.expandingNodeId && (
              <span className="text-primary animate-pulse">Loading…</span>
            )}
            {exploration.expandedNodeIds.length > 0 && (
              <button
                onClick={() => exploration.reset()}
                className="text-primary hover:underline cursor-pointer"
                data-testid="graph-reset-button"
              >
                Reset
              </button>
            )}
          </div>
        }
      />

      {/* Context menu */}
      {menu && (
        <NodeContextMenu
          menu={menu}
          onClose={() => setMenu(null)}
          onProperties={() => {
            inspect({ type: "node", id: menu.node.id });
            setMenu(null);
          }}
          onExpand={
            expansion && exploration.canExpand(menu.node.id)
              ? () =>
                  exploration
                    .onExpandRequest(menu.node)
                    // fetchNeighbors throws an Error with the reason.
                    .catch((err: Error) =>
                      toast({
                        title: "Expand failed",
                        description: err.message,
                        variant: "destructive",
                      }),
                    )
              : undefined
          }
          onCollapse={
            exploration.canCollapse(menu.node.id)
              ? () => exploration.collapse(menu.node.id)
              : undefined
          }
        />
      )}

      {inspector && (
        <GraphInspector
          element={inspector.element}
          elementJson={inspector.elementJson}
          connections={inspector.connections}
          side={side}
          width={inspectorWidth}
          onClose={closeInspector}
          onSelectNode={inspectNode}
          onSelectRelationship={inspectRelationship}
          onCopied={(what) => toast({ title: `Copied ${what}` })}
          onCopyBlocked={() =>
            toast({
              title: "The browser blocked the clipboard",
              description:
                "The text is selected: press Ctrl+C, or Cmd+C on a Mac.",
            })
          }
        />
      )}
    </div>
  );
}
