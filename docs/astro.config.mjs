import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";
import rehypeBaseLinks from "./rehype-base-links.mjs";

// Published as a GitHub Pages project site (#1318): docs-pages.yml sets
// DOCS_SITE=https://<owner, lowercased>.github.io and DOCS_BASE=/<repo>, and
// docs-ci.yml builds the same way. Locally both are unset, so the site serves
// from / and emits no sitemap.
const site = process.env.DOCS_SITE || undefined;
const base = process.env.DOCS_BASE || "/";

/**
 * Two Starlight breaking changes are handled here, both introduced between
 * 0.31.1 and 0.41.5 (#1461):
 *
 * - **0.33.0** — `social` takes an array of link items, not an object.
 * - **0.39.0** — autogenerated sidebar groups can no longer carry a `label`
 *   alongside `autogenerate`. The label now belongs to a group whose `items`
 *   contains the autogenerate config.
 *
 * Seven groups, one directory each, in reading order (#1681). Ordering inside
 * a group comes from `sidebar.order` in every page's frontmatter — a group's
 * first page is its landing; there are no index pages.
 */
export default defineConfig({
  site,
  base,
  // Content links are root-absolute; Astro does not prefix `base` onto them.
  markdown: { rehypePlugins: [[rehypeBaseLinks, { base }]] },
  integrations: [
    starlight({
      title: "NeoBoard",
      description: "Open-source dashboarding for Neo4j & PostgreSQL",
      // The wordmark's citrine square (#1319); public/favicon.svg is the same
      // mark at Starlight's default favicon path.
      logo: { src: "./src/assets/mark.svg", alt: "" },
      customCss: ["./src/styles/brand.css"],
      social: [
        {
          icon: "github",
          label: "GitHub",
          href: "https://github.com/alfredo1996/neoboard",
        },
      ],
      sidebar: [
        {
          label: "Start here",
          items: [{ autogenerate: { directory: "start-here" } }],
        },
        {
          label: "Using NeoBoard",
          items: [{ autogenerate: { directory: "using" } }],
        },
        {
          label: "Chart types",
          items: [{ autogenerate: { directory: "charts" } }],
        },
        {
          label: "Deploy and operate",
          items: [{ autogenerate: { directory: "deploy" } }],
        },
        {
          label: "Security and access",
          items: [{ autogenerate: { directory: "security" } }],
        },
        {
          label: "CLI",
          items: [{ autogenerate: { directory: "cli" } }],
        },
        {
          label: "Extend and contribute",
          items: [{ autogenerate: { directory: "extend" } }],
        },
      ],
    }),
  ],
});
